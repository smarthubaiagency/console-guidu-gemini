package context

import (
	"context"
	"time"

	"github.com/cartaopro/mcp/internal/execution"
	"github.com/cartaopro/mcp/internal/observability/requestid"
)

// MCPContext represents the immutable execution context for MCP operations.
// Fields are set only via NewEnvelope — no mutations after construction.
type MCPContext struct {
	RequestID   string
	ExecutionID execution.ID // unique trace ID for this execution, set at construction
	WorkspaceID string
	UserID      string
	Type        string // user | agent | system | integration
	Roles       []string
	Source      string // api | agent | webhook | system
	Permissions []string
	Timestamp   time.Time

	// goCtx is the underlying Go context (request lifecycle, cancellation, tenant claims).
	// Unexported to prevent mutation; access via GoContext().
	goCtx context.Context
}

// GoContext returns the underlying Go context.Context associated with this execution.
// This is the context that carries tenant claims, cancellation signals, and deadlines.
// Domain tools must use this context when calling repositories or any I/O operation.
func (m MCPContext) GoContext() context.Context {
	if m.goCtx == nil {
		return context.Background()
	}
	return m.goCtx
}

// NewEnvelope derives an MCPContext from a standard context.Context.
// execID must be generated by the caller via execution.NewID() before invoking this.
func NewEnvelope(ctx context.Context, workspaceID, userID, idType, source string, execID execution.ID) MCPContext {
	return MCPContext{
		RequestID:   requestid.FromContext(ctx),
		ExecutionID: execID,
		WorkspaceID: workspaceID,
		UserID:      userID,
		Type:        idType,
		Source:      source,
		Timestamp:   time.Now().UTC(),
		goCtx:       ctx,
	}
}
