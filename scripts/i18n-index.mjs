// Regenerates src/i18n/messages/index.ts from the namespace files of each
// language (I2): `node scripts/i18n-index.mjs`. A unit test fails when the
// index and the files disagree.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = "src/i18n/messages";
const LOCALES = ["pt-BR", "en", "es"];
const ident = (locale, ns) =>
  `${locale.replace(/[^a-zA-Z]/g, "")}_${ns.replace(/[^a-zA-Z0-9]/g, "_")}`;

const namespaces = readdirSync(join(ROOT, "pt-BR"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.slice(0, -5))
  .sort();

const lines = [
  "// Generated by scripts/i18n-index.mjs; do not edit by hand.",
  "",
];
for (const locale of LOCALES) {
  for (const ns of namespaces) {
    lines.push(`import ${ident(locale, ns)} from "./${locale}/${ns}.json";`);
  }
}
lines.push("", "/** Texts shipped in the code, per language and namespace. */");
lines.push("export const MESSAGE_FILES = {");
for (const locale of LOCALES) {
  lines.push(`  "${locale}": {`);
  for (const ns of namespaces) lines.push(`    "${ns}": ${ident(locale, ns)},`);
  lines.push("  },");
}
lines.push("} as const;", "");
lines.push(`export const NAMESPACES = ${JSON.stringify(namespaces)} as const;`, "");
writeFileSync(join(ROOT, "index.ts"), lines.join("\n"));
console.log(`${namespaces.length} namespaces x ${LOCALES.length} languages`);
