-- 5. Audit of automatic changes
-- ----------------------------------------------------------------------------
-- A platform job records what it changed as a service of the worker, never
-- in a user's or workspace's name, at the current time.
create policy audit_events_worker_insert on public.audit_events
  for insert to app_worker
  with check (
    actor_principal_type = 'service'
    and actor_user_id is null
    and represented_user_id is null
    and grant_id is null
    and workspace_id is null
    and origin = 'worker'
    and occurred_at >= (now() - interval '5 minutes')
    and occurred_at <= (now() + interval '1 minute')
  );

grant insert on public.audit_events to app_worker;
