-- 2. Notification deliveries
-- ----------------------------------------------------------------------------
create table public.notification_deliveries (
  id              uuid primary key default gen_random_uuid(),
  partner_id      uuid not null references public.partners(id) on delete cascade,
  event_type      text not null check (event_type ~ '^[a-z]+(\.[a-z_]+)+$' and length(event_type) <= 80),
  recipient_email text not null check (length(recipient_email) between 3 and 254),
  subject         text not null check (length(subject) between 1 and 200),
  idempotency_key text not null unique check (length(idempotency_key) between 1 and 200),
  related_id      uuid,
  status          text not null default 'pending' check (status in ('pending', 'sent', 'skipped', 'failed')),
  reason          text check (reason is null or length(reason) <= 200),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create index notification_deliveries_partner_idx
  on public.notification_deliveries (partner_id, created_at desc);

alter table public.notification_deliveries owner to app_migrations;
