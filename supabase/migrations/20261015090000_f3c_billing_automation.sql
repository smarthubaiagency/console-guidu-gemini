-- Maintenance Rationale:
-- 1. `public.billing_settings`: one row with the provisional terms of
--    decision 4 (3 days of tolerance after the period end before "em
--    atraso", 7 more days before "suspensa"). Platform billing edits it.
-- 2. `public.notification_deliveries`: every notice, unique per
--    idempotency key, with its outcome (`skipped` while no e-mail provider
--    exists, D-PA-08). Read by the platform and by the partner it concerns.
-- 3. `public.payout_reports`: totals per partner and month, generated by a
--    job, unique per partner and period.
-- 4. Platform jobs act without a user, as `app_worker`, through narrow
--    policies of their own: read subscriptions and the few columns notices
--    need (column grants), move subscriptions from active to past due and
--    from past due to suspended (the P5m trigger still validates every
--    transition), and write deliveries and reports. The web runtime cannot
--    become app_worker, so none of this reaches it. Jobs requested by users
--    keep running as app_runtime in the requester's context (F3a).
-- 5. Platform jobs audit what they change as a worker service (no user,
--    no workspace).
-- Owner app_migrations, ENABLE + FORCE RLS, no grants to anon/authenticated.
-- The settings row is seeded before RLS is enabled.
